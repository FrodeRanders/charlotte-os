const REPLY_SPINS: u64 = 50_000_000;
// The kernel-assigned base of the delegated virtio BAR, set once at map
// time. The device-config/ISR/doorbell helpers must read it: the old fixed
// 0x400000 vaddr was not the mapped base and dereferenced stale addresses.
static MMIO_BASE: core::sync::atomic::AtomicUsize = core::sync::atomic::AtomicUsize::new(0);
// Keep transient mappings clear of the loader's per-shard CQ region at
// 0x0080_0000 and the userspace stack arena at 0x0100_0000.
const PAGE_SIZE: usize = 4096;
const BUFFER_SIZE: usize = 2048;
// The modern QEMU transport uses the v1 header including the trailing
// num_buffers field on both transmit and receive.
const VIRTIO_NET_TX_HEADER_SIZE: usize = 12;
const VIRTIO_NET_RX_HEADER_SIZE: usize = 12;
const MAX_FRAME_SIZE: usize = BUFFER_SIZE - VIRTIO_NET_TX_HEADER_SIZE;
/// Minimum Ethernet frame size presented to a NIC, excluding the four-byte
/// frame check sequence generated by hardware.
const MIN_ETHERNET_FRAME_SIZE: usize = 60;
const MAX_QUEUE_SIZE: u16 = 256;

/// Publish split-ring updates to a DMA observer before the subsequent index
/// update or queue notification. On AArch64 an outer-shareable `dmb` is needed
/// to order normal memory against Device MMIO; x86_64 is strongly ordered and
/// a release fence is sufficient.
#[inline]
fn dma_write_barrier() {
    #[cfg(target_arch = "aarch64")]
    unsafe {
        asm!("dmb oshst", options(nostack, preserves_flags))
    }
    #[cfg(not(target_arch = "aarch64"))]
    core::sync::atomic::fence(core::sync::atomic::Ordering::Release)
}

/// Order reads from a device-written DMA ring after observing its producer
/// index. The producer index is the ownership handoff: once it advances, the
/// corresponding used-ring entries and packet buffers must be observed after
/// that handoff rather than speculatively before it.
#[inline]
fn dma_read_barrier() {
    #[cfg(target_arch = "aarch64")]
    unsafe {
        asm!("dmb oshld", options(nostack, preserves_flags))
    }
    #[cfg(not(target_arch = "aarch64"))]
    core::sync::atomic::fence(core::sync::atomic::Ordering::Acquire)
}

#[inline]
unsafe fn r8(a: usize) -> u8 {
    unsafe { core::ptr::read_volatile(a as *const u8) }
}
#[inline]
unsafe fn r16(a: usize) -> u16 {
    unsafe { core::ptr::read_volatile(a as *const u16) }
}
#[inline]
unsafe fn r32(a: usize) -> u32 {
    unsafe { core::ptr::read_volatile(a as *const u32) }
}
#[inline]
unsafe fn w8(a: usize, v: u8) {
    unsafe { core::ptr::write_volatile(a as *mut u8, v) }
}
#[inline]
unsafe fn w16(a: usize, v: u16) {
    unsafe { core::ptr::write_volatile(a as *mut u16, v) }
}
#[inline]
unsafe fn w32(a: usize, v: u32) {
    unsafe { core::ptr::write_volatile(a as *mut u32, v) }
}

#[inline]
unsafe fn w64(a: usize, v: u64) {
    // The virtio PCI capability only guarantees naturally aligned accesses
    // up to 32 bits. Program 64-bit queue addresses as little-endian halves;
    // QEMU (and physical transitional devices) may ignore an 8-byte MMIO
    // transaction even though the field itself is 64 bits wide.
    unsafe {
        w32(a, v as u32);
        w32(a + 4, (v >> 32) as u32);
    }
}

/// Allocate memory, map it at a kernel-assigned scratch address, and map
/// it into the driver's DMA domain. Returns `(cap, iova, iova_pfn, vaddr)`.
unsafe fn alloc_dma(
    dma_domain: u64,
    pages: usize,
    direction: DmaDirection,
) -> (u64, u64, u32, usize) {
    let cap = memory_alloc(pages);
    if cap == 0 {
        return (0, 0, 0, 0);
    }
    let (map_status, vaddr) = memory_map_any(cap, true);
    if map_status != 0 {
        memory_close(cap);
        return (0, 0, 0, 0);
    }
    // SAFETY: queue memory is accessed only through this driver's volatile
    // descriptor protocol and remains mapped and pinned until queue teardown.
    let iova = unsafe { dma_map(dma_domain, cap, direction) };
    if iova == 0 {
        memory_unmap(cap);
        memory_close(cap);
        return (0, 0, 0, 0);
    }
    let pfn = (iova >> 12) as u32;
    (cap, iova, pfn, vaddr)
}

#[inline]
fn avail_offset(queue_size: u16) -> usize {
    queue_size as usize * virtio::DESC_SIZE
}

#[inline]
fn used_offset(queue_size: u16) -> usize {
    let avail_end = avail_offset(queue_size) + 6 + queue_size as usize * 2;
    avail_end.next_multiple_of(PAGE_SIZE)
}

#[inline]
fn vring_pages(queue_size: u16) -> usize {
    let used_end = used_offset(queue_size) + 6 + queue_size as usize * 8;
    used_end.div_ceil(PAGE_SIZE)
}

unsafe fn zero_vq(page_va: usize, queue_size: u16) {
    unsafe {
        core::ptr::write_bytes(page_va as *mut u8, 0, vring_pages(queue_size) * PAGE_SIZE);
    }
}

unsafe fn select_vq(bar0: usize, q: u16) -> u16 {
    unsafe { w16(bar0 + virtio::M_QUEUE_SELECT, q) };
    unsafe { r16(bar0 + virtio::M_QUEUE_SIZE) }
}

/// Set up a modern split virtqueue and return its queue-notify offset.
unsafe fn cfg_vq(bar0: usize, q: u16, ring_iova: u64, queue_size: u16) -> u16 {
    unsafe {
        w16(bar0 + virtio::M_QUEUE_SELECT, q);
        w16(bar0 + virtio::M_QUEUE_VECTOR, 0);
        w16(bar0 + virtio::M_QUEUE_SIZE, queue_size);
        w64(bar0 + virtio::M_QUEUE_DESC, ring_iova);
        w64(bar0 + virtio::M_QUEUE_DRIVER, ring_iova + avail_offset(queue_size) as u64);
        w64(bar0 + virtio::M_QUEUE_DEVICE, ring_iova + used_offset(queue_size) as u64);
        w16(bar0 + virtio::M_QUEUE_ENABLE, 1);
    }
    unsafe { r16(bar0 + virtio::M_QUEUE_NOTIFY_OFF) }
}

#[inline]
unsafe fn notify(queue: u16, notify_offset: u16) {
    unsafe {
        w32(
            MMIO_BASE.load(core::sync::atomic::Ordering::Relaxed)
                + virtio::MODERN_NOTIFY
                + notify_offset as usize * virtio::MODERN_NOTIFY_MULTIPLIER,
            queue as u32,
        )
    }
}

struct ReceivedFrame {
    cap: u64,
    len: usize,
}

fn deliver_received(queue: &mut VecDeque<ReceivedFrame>, pending_recv: &mut u64) {
    if *pending_recv == 0 {
        return;
    }
    let Some(frame) = queue.pop_front() else {
        return;
    };
    if ipc_reply_move(*pending_recv, frame.cap, frame.len as i64) != 0 {
        memory_close(frame.cap);
    }
    *pending_recv = 0;
}

unsafe fn drain_rx(
    notify_offset: u16,
    queue_size: u16,
    header_size: usize,
    rx_desc_vaddr: usize,
    rx_buf_vaddr: usize,
    used_seen: &mut u16,
    queue: &mut VecDeque<ReceivedFrame>,
) {
    let used = rx_desc_vaddr + used_offset(queue_size);
    let device_idx = unsafe { r16(used + virtio::USED_IDX) };
    dma_read_barrier();
    let mut recycled = false;
    while *used_seen != device_idx {
        let slot = *used_seen as usize % queue_size as usize;
        let elem = used + virtio::USED_RING + slot * 8;
        let desc_id = unsafe { r32(elem) } as usize;
        let used_len = unsafe { r32(elem + 4) } as usize;
        if desc_id < queue_size as usize && (header_size..=BUFFER_SIZE).contains(&used_len) {
            let frame_len = used_len - header_size;
            let cap = memory_alloc(1);
            if cap != 0 {
                let (v_reply_map_status, v_reply_vaddr) = memory_map_any(cap, true);
                if v_reply_map_status == 0 {
                    unsafe {
                        core::ptr::copy_nonoverlapping(
                            (rx_buf_vaddr + desc_id * BUFFER_SIZE + header_size) as *const u8,
                            v_reply_vaddr as *mut u8,
                            frame_len,
                        );
                    }
                    memory_unmap(cap);
                    queue.push_back(ReceivedFrame {
                        cap,
                        len: frame_len,
                    });
                } else if cap != 0 {
                    memory_close(cap);
                }
            }
        }

        if desc_id < queue_size as usize {
            let avail = rx_desc_vaddr + avail_offset(queue_size);
            let avail_idx = unsafe { r16(avail + virtio::AVAIL_IDX) };
            unsafe {
                w16(
                    avail + virtio::AVAIL_RING + (avail_idx as usize % queue_size as usize) * 2,
                    desc_id as u16,
                );
            }
            dma_write_barrier();
            unsafe { w16(avail + virtio::AVAIL_IDX, avail_idx.wrapping_add(1)) };
            recycled = true;
        }
        *used_seen = used_seen.wrapping_add(1);
    }
    if recycled {
        dma_write_barrier();
        unsafe { notify(virtio::VIRTQ_RX, notify_offset) };
    }
}

unsafe fn drain_tx(
    queue_size: u16,
    tx_desc_vaddr: usize,
    used_seen: &mut u16,
    in_use: &mut [bool],
) {
    let used = tx_desc_vaddr + used_offset(queue_size);
    let device_idx = unsafe { r16(used + virtio::USED_IDX) };
    dma_read_barrier();
    while *used_seen != device_idx {
        let slot = *used_seen as usize % queue_size as usize;
        let desc_id = unsafe { r32(used + virtio::USED_RING + slot * 8) } as usize;
        if let Some(state) = in_use.get_mut(desc_id) {
            *state = false;
        }
        *used_seen = used_seen.wrapping_add(1);
    }
}

fn main(ctx: Context) -> ! {
    config::write::<u32>(status::STAGE, 1);
    let ns_conn = match ctx.bootstrap_cap() {
        Some(c) => c,
        None => unsafe { thread_exit() },
    };
    let mmio_cap = match ctx.mmio_cap() {
        Some(c) => c,
        None => unsafe { thread_exit() },
    };
    let irq_cap = match ctx.irq_cap() {
        Some(c) => c,
        None => unsafe { thread_exit() },
    };
    let dma_domain = match config::dma_domain_cap() {
        Some(c) => c,
        None => unsafe { thread_exit() },
    };
    config::write::<u32>(status::STAGE, 2);
    let (mmio_map_status, vaddr_bar0) = device_mmio_map_any(mmio_cap, true);
    if mmio_map_status != 0 {
        catten_syscall::el0_log(0x4e45_5454, 0x4d4d_494f | mmio_map_status);
        unsafe { thread_exit() };
    }
    MMIO_BASE.store(vaddr_bar0, core::sync::atomic::Ordering::Relaxed);
    config::write::<u32>(status::STAGE, 3);
    let bar0 = vaddr_bar0 + virtio::MODERN_COMMON;

    // --- virtio PCI modern initialization ---
    unsafe { w8(bar0 + virtio::M_DEVICE_STATUS, 0) };
    unsafe { w8(bar0 + virtio::M_DEVICE_STATUS, virtio::STATUS_ACKNOWLEDGE) };
    unsafe {
        w8(bar0 + virtio::M_DEVICE_STATUS, virtio::STATUS_ACKNOWLEDGE | virtio::STATUS_DRIVER)
    };
    unsafe { w32(bar0 + virtio::M_DEVICE_FEATURE_SELECT, 0) };
    let device_features_lo = unsafe { r32(bar0 + virtio::M_DEVICE_FEATURE) };
    unsafe { w32(bar0 + virtio::M_DEVICE_FEATURE_SELECT, 1) };
    let device_features_hi = unsafe { r32(bar0 + virtio::M_DEVICE_FEATURE) };
    // Every descriptor owns a full-size frame buffer, so no packet actually
    // needs multiple receive buffers even though the modern header retains
    // its trailing num_buffers field.
    let guest_features_lo = device_features_lo & (virtio::FEATURE_MAC | virtio::FEATURE_STATUS);
    let rx_header_size = VIRTIO_NET_RX_HEADER_SIZE;
    let required_hi = virtio::FEATURE_VERSION_1 | virtio::FEATURE_ACCESS_PLATFORM;
    if device_features_hi & required_hi != required_hi {
        unsafe { thread_exit() };
    }
    unsafe {
        w32(bar0 + virtio::M_DRIVER_FEATURE_SELECT, 0);
        w32(bar0 + virtio::M_DRIVER_FEATURE, guest_features_lo);
        w32(bar0 + virtio::M_DRIVER_FEATURE_SELECT, 1);
        w32(bar0 + virtio::M_DRIVER_FEATURE, required_hi);
    }
    unsafe {
        w8(
            bar0 + virtio::M_DEVICE_STATUS,
            virtio::STATUS_ACKNOWLEDGE | virtio::STATUS_DRIVER | virtio::STATUS_FEATURES_OK,
        )
    };
    if unsafe { r8(bar0 + virtio::M_DEVICE_STATUS) & virtio::STATUS_FEATURES_OK == 0 } {
        unsafe { thread_exit() };
    }

    // Read MAC.
    let dc = MMIO_BASE.load(core::sync::atomic::Ordering::Relaxed) + virtio::MODERN_DEVICE;
    for i in 0..6 {
        config::write::<u8>(status::MAC + i, unsafe { r8(dc + virtio::NET_MAC + i) });
    }
    config::write::<u16>(status::LINK, unsafe { r16(dc + virtio::NET_STATUS) });
    config::write::<u32>(status::STAGE, 4);

    // --- virtqueues ---------------------------------------------------------
    unsafe { w16(bar0 + virtio::M_CONFIG_VECTOR, 0) };
    let rx_qsz = unsafe { select_vq(bar0, virtio::VIRTQ_RX) };
    let tx_qsz = unsafe { select_vq(bar0, virtio::VIRTQ_TX) };
    if rx_qsz == 0 || tx_qsz == 0 || rx_qsz > MAX_QUEUE_SIZE || tx_qsz > MAX_QUEUE_SIZE {
        unsafe { thread_exit() };
    }
    let (rx_cap, rx_ring_iova, _, rx_desc_vaddr) =
        unsafe { alloc_dma(dma_domain, vring_pages(rx_qsz), DmaDirection::Bidirectional) };
    let (tx_cap, tx_ring_iova, _, tx_desc_vaddr) =
        unsafe { alloc_dma(dma_domain, vring_pages(tx_qsz), DmaDirection::Bidirectional) };
    let rx_buffer_pages = (rx_qsz as usize * BUFFER_SIZE).div_ceil(PAGE_SIZE);
    let tx_buffer_pages = (tx_qsz as usize * BUFFER_SIZE).div_ceil(PAGE_SIZE);
    let (rx_buf_cap, rx_buf_iova, _, rx_buf_vaddr) =
        unsafe { alloc_dma(dma_domain, rx_buffer_pages, DmaDirection::DeviceWrite) };
    let (tx_buf_cap, tx_buf_iova, _, tx_buf_vaddr) =
        unsafe { alloc_dma(dma_domain, tx_buffer_pages, DmaDirection::DeviceRead) };
    if rx_cap == 0 || tx_cap == 0 || rx_buf_cap == 0 || tx_buf_cap == 0 {
        unsafe { thread_exit() };
    }
    unsafe { zero_vq(rx_desc_vaddr, rx_qsz) };
    unsafe { zero_vq(tx_desc_vaddr, tx_qsz) };
    let rx_avail = rx_desc_vaddr + avail_offset(rx_qsz);
    for i in 0..rx_qsz as usize {
        unsafe {
            w32(
                rx_desc_vaddr + i * virtio::DESC_SIZE + virtio::DESC_ADDR_LO,
                (rx_buf_iova + (i * BUFFER_SIZE) as u64) as u32,
            );
            w32(
                rx_desc_vaddr + i * virtio::DESC_SIZE + virtio::DESC_ADDR_HI,
                ((rx_buf_iova + (i * BUFFER_SIZE) as u64) >> 32) as u32,
            );
            w32(rx_desc_vaddr + i * virtio::DESC_SIZE + virtio::DESC_LENGTH, BUFFER_SIZE as u32);
            w16(
                rx_desc_vaddr + i * virtio::DESC_SIZE + virtio::DESC_FLAGS,
                virtio::VRING_DESC_F_WRITE,
            );
            w16(rx_avail + virtio::AVAIL_RING + i * 2, i as u16);
        }
    }
    dma_write_barrier();
    unsafe { w16(rx_avail + virtio::AVAIL_IDX, rx_qsz) };
    let rx_notify = unsafe { cfg_vq(bar0, virtio::VIRTQ_RX, rx_ring_iova, rx_qsz) };
    let tx_notify = unsafe { cfg_vq(bar0, virtio::VIRTQ_TX, tx_ring_iova, tx_qsz) };
    config::write::<u16>(status::RX_NOTIFY, rx_notify);
    config::write::<u16>(status::TX_NOTIFY, tx_notify);
    unsafe { w16(bar0 + virtio::M_QUEUE_SELECT, virtio::VIRTQ_RX) };
    config::write::<u16>(status::RX_QUEUE_ENABLED, unsafe { r16(bar0 + virtio::M_QUEUE_ENABLE) });
    unsafe { w16(bar0 + virtio::M_QUEUE_SELECT, virtio::VIRTQ_TX) };
    config::write::<u16>(status::TX_QUEUE_ENABLED, unsafe { r16(bar0 + virtio::M_QUEUE_ENABLE) });
    config::write::<u32>(status::RX_RING_PFN, (rx_ring_iova >> 12) as u32);
    config::write::<u32>(status::TX_RING_PFN, (tx_ring_iova >> 12) as u32);
    config::write::<u32>(status::STAGE, 5); // virtqueues set up

    // DRIVER_OK
    unsafe {
        w8(
            bar0 + virtio::M_DEVICE_STATUS,
            virtio::STATUS_ACKNOWLEDGE
                | virtio::STATUS_DRIVER
                | virtio::STATUS_DRIVER_OK
                | virtio::STATUS_FEATURES_OK,
        )
    };
    // Publish the pre-filled receive ring. Some legacy transports do not
    // inspect it until the driver explicitly kicks queue 0.
    dma_write_barrier();
    unsafe { notify(virtio::VIRTQ_RX, rx_notify) };
    config::write::<u32>(status::STAGE, 6);

    // --- Register endpoint --------------------------------------------------
    let ep = ipc_endpoint_create(net::INTERFACE, net::VERSION, 8);
    if ep == 0 {
        unsafe { thread_exit() };
    }
    let reg = ipc_scalar_call_connection(
        ns_conn,
        ns::OP_REGISTER,
        net::NAME,
        ep,
        IpcRights::SEND | IpcRights::CALL | IpcRights::MINT_CONNECTION,
    );
    if reg == 0 {
        unsafe { thread_exit() };
    }
    let (generation, _) = unsafe { wait_reply(reg, REPLY_SPINS) };
    if generation < 1 {
        unsafe { thread_exit() };
    }
    config::write::<u32>(status::STAGE, 7);

    if ipc_endpoint_bind_cq(ep, 0) != 0 {
        unsafe { thread_exit() };
    }
    if device_irq_bind_cq(irq_cap, 0) != 0 {
        unsafe { thread_exit() };
    }
    config::write::<u32>(status::STAGE, 8);

    // --- State ---------------------------------------------------------------
    let mut tx_avail_idx: u16 = 0;
    let mut tx_used_seen: u16 = 0;
    let mut rx_used_seen: u16 = 0;
    let mut tx_in_use = vec![false; tx_qsz as usize];
    let mut received = VecDeque::new();
    let mut pending_recv: u64 = 0;

    loop {
        // Interrupts are the normal wakeup path. The bounded poll also
        // recovers if a legacy virtio implementation suppresses an edge
        // while descriptors are being published.
        let _ = cq_wait_timeout(1, 10, 0);
        let (_s, _c) = device_irq_ack(irq_cap);
        let _ = unsafe {
            r8(MMIO_BASE.load(core::sync::atomic::Ordering::Relaxed) + virtio::MODERN_ISR)
        };
        unsafe {
            drain_tx(tx_qsz, tx_desc_vaddr, &mut tx_used_seen, &mut tx_in_use);
            drain_rx(
                rx_notify,
                rx_qsz,
                rx_header_size,
                rx_desc_vaddr,
                rx_buf_vaddr,
                &mut rx_used_seen,
                &mut received,
            );
        }
        config::write::<u16>(status::RX_USED_SEEN, rx_used_seen);
        config::write::<u16>(status::TX_USED_SEEN, tx_used_seen);
        config::write::<u8>(status::DEVICE_STATUS, unsafe { r8(bar0 + virtio::M_DEVICE_STATUS) });
        config::write::<u16>(status::TX_AVAILABLE, tx_avail_idx);
        // RX-ring diagnostic: descriptors the device has filled but the driver
        // has not yet recycled. When this reaches `rx_qsz` the available ring
        // is empty, so virtio-net has no RX buffer and queues incoming frames
        // (the trigger for the socket/stream read-poll disable).
        let device_used_idx =
            unsafe { r16(rx_desc_vaddr + used_offset(rx_qsz) + virtio::USED_IDX) };
        let rx_unrecycled = device_used_idx.wrapping_sub(rx_used_seen);
        config::write::<u16>(status::RX_UNRECYCLED, rx_unrecycled);
        config::write::<u16>(status::RX_QUEUE_SIZE, rx_qsz);
        deliver_received(&mut received, &mut pending_recv);

        // --- endpoint messages ---------------------------------------------
        loop {
            let m = ipc_recv(ep);
            if m.status == ipc_status::NO_MESSAGE {
                break;
            }
            if m.status == ipc_status::ENDPOINT_CLOSED {
                unsafe { thread_exit() };
            }
            if !m.is_ok() {
                break;
            }
            match m.opcode {
                net::OP_STATUS => {
                    if m.reply != 0 {
                        let d = MMIO_BASE.load(core::sync::atomic::Ordering::Relaxed)
                            + virtio::MODERN_DEVICE;
                        let mac = [
                            unsafe { r8(d + virtio::NET_MAC) } as u64,
                            unsafe { r8(d + virtio::NET_MAC + 1) } as u64,
                            unsafe { r8(d + virtio::NET_MAC + 2) } as u64,
                            unsafe { r8(d + virtio::NET_MAC + 3) } as u64,
                            unsafe { r8(d + virtio::NET_MAC + 4) } as u64,
                            unsafe { r8(d + virtio::NET_MAC + 5) } as u64,
                        ];
                        let link = unsafe { r16(d + virtio::NET_STATUS) } as u64;
                        let result = (link & 1)
                            | (mac[0] << 8)
                            | (mac[1] << 16)
                            | (mac[2] << 24)
                            | (mac[3] << 32)
                            | (mac[4] << 40)
                            | (mac[5] << 48);
                        ipc_reply(m.reply, result as i64);
                    }
                }
                net::OP_SEND => {
                    let frame_len = m.arg0 as usize;
                    let Some(desc_id) = tx_in_use.iter().position(|used| !*used) else {
                        config::write::<u32>(status::TX_PROGRESS, 1);
                        if m.memory != 0 {
                            memory_close(m.memory);
                        }
                        if m.reply != 0 {
                            ipc_reply(m.reply, -1);
                        }
                        continue;
                    };
                    if m.memory == 0 || !(14..=MAX_FRAME_SIZE).contains(&frame_len) {
                        config::write::<u32>(status::TX_PROGRESS, 2);
                        if m.memory != 0 {
                            memory_close(m.memory);
                        }
                        if m.reply != 0 {
                            ipc_reply(m.reply, -1);
                        }
                        continue;
                    }
                    let (v_input_map_status, v_input_vaddr) = memory_map_any(m.memory, false);
                    if v_input_map_status != 0 {
                        config::write::<u32>(status::TX_PROGRESS, 3);
                        memory_close(m.memory);
                        if m.reply != 0 {
                            ipc_reply(m.reply, -1);
                        }
                        continue;
                    }
                    let tx_slot = tx_buf_vaddr + desc_id * BUFFER_SIZE;
                    let wire_len = frame_len.max(MIN_ETHERNET_FRAME_SIZE);
                    unsafe {
                        core::ptr::write_bytes(
                            tx_slot as *mut u8,
                            0,
                            VIRTIO_NET_TX_HEADER_SIZE + wire_len,
                        );
                        core::ptr::copy_nonoverlapping(
                            v_input_vaddr as *const u8,
                            (tx_slot + VIRTIO_NET_TX_HEADER_SIZE) as *mut u8,
                            frame_len,
                        );
                    }
                    memory_unmap(m.memory);
                    memory_close(m.memory);

                    let desc_iova = tx_buf_iova + (desc_id * BUFFER_SIZE) as u64;
                    let off = desc_id * virtio::DESC_SIZE;
                    unsafe {
                        w32(tx_desc_vaddr + off + virtio::DESC_ADDR_LO, desc_iova as u32);
                        w32(tx_desc_vaddr + off + virtio::DESC_ADDR_HI, (desc_iova >> 32) as u32);
                        w32(
                            tx_desc_vaddr + off + virtio::DESC_LENGTH,
                            (VIRTIO_NET_TX_HEADER_SIZE + wire_len) as u32,
                        );
                        w16(tx_desc_vaddr + off + virtio::DESC_FLAGS, 0);
                    }
                    let tx_avail = tx_desc_vaddr + avail_offset(tx_qsz);
                    unsafe {
                        w16(
                            tx_avail
                                + virtio::AVAIL_RING
                                + (tx_avail_idx as usize % tx_qsz as usize) * 2,
                            desc_id as u16,
                        );
                    }
                    tx_in_use[desc_id] = true;
                    dma_write_barrier();
                    tx_avail_idx = tx_avail_idx.wrapping_add(1);
                    config::write::<u16>(status::TX_AVAILABLE, tx_avail_idx);
                    unsafe {
                        w16(tx_avail + virtio::AVAIL_IDX, tx_avail_idx);
                        dma_write_barrier();
                        notify(virtio::VIRTQ_TX, tx_notify);
                    }
                    if m.reply != 0 {
                        config::write::<u32>(status::TX_PROGRESS, 4);
                        ipc_reply(m.reply, 0);
                    }
                }
                net::OP_RECV => {
                    if m.reply != 0 && pending_recv == 0 {
                        pending_recv = m.reply;
                        deliver_received(&mut received, &mut pending_recv);
                    } else if m.reply != 0 {
                        ipc_reply(m.reply, -1);
                    }
                }
                net::OP_SHUTDOWN => {
                    if m.reply != 0 {
                        ipc_reply(m.reply, 0);
                    }
                    unsafe {
                        device_mmio_unmap(mmio_cap);
                        catten_syscall::device_close(irq_cap);
                        thread_exit();
                    }
                }
                _ => {
                    if m.reply != 0 {
                        ipc_reply(m.reply, -1);
                    }
                }
            }
        }
    }
}

